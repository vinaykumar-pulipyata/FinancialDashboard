-- Monthly spending limits: one row per category (a main category, which also covers its sub categories) and at most one row with no
-- category, the limit on all spending. The same limit applies to every month. The service keeps a category to one row.
CREATE TABLE budget (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT,
    amount NUMERIC(19, 2) NOT NULL
);
