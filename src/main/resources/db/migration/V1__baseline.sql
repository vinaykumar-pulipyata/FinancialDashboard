-- The schema as Hibernate built it before Flyway took over (taken from a backup of a running database).
-- A database that already has these tables is baselined at version 1 and this file is skipped (spring.flyway.baseline-on-migrate);
-- a blank database gets them from here. From now on every schema change is a new V<n>__<what>.sql file; never edit this one.

CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active BOOLEAN NOT NULL,
    level INTEGER NOT NULL,
    name VARCHAR(255) NOT NULL,
    notes VARCHAR(1000),
    opening_balance NUMERIC(19, 2) NOT NULL,
    parent_id BIGINT,
    target_amount NUMERIC(19, 2),
    type ENUM('BANK', 'CASH', 'CREDIT_CARD', 'DEBT', 'GOAL_FUND', 'GOLD', 'INVESTMENT', 'OTHER', 'PROPERTY', 'RECEIVABLE', 'VEHICLE') NOT NULL
);

CREATE TABLE app_credential (
    id BIGINT PRIMARY KEY,
    password_hash VARCHAR(255) NOT NULL
);

CREATE TABLE app_setting (
    setting_key VARCHAR(100) PRIMARY KEY,
    setting_value VARCHAR(1000)
);

CREATE TABLE borrower (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    opening_amount NUMERIC(19, 2) NOT NULL
);

CREATE TABLE category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active BOOLEAN NOT NULL,
    kind ENUM('EXPENSE', 'INCOME') NOT NULL,
    name VARCHAR(255) NOT NULL,
    parent_id BIGINT,
    system_key VARCHAR(30)
);

CREATE TABLE credit_card_detail (
    account_id BIGINT PRIMARY KEY,
    credit_limit NUMERIC(19, 2) NOT NULL,
    due_day INTEGER
);

CREATE TABLE debt_detail (
    account_id BIGINT PRIMARY KEY,
    emi_amount NUMERIC(19, 2) NOT NULL
);

CREATE TABLE emergency_fund_detail (
    account_id BIGINT PRIMARY KEY,
    monthly_essential_expenses NUMERIC(19, 2),
    planned_monthly_contribution NUMERIC(19, 2),
    target_amount NUMERIC(19, 2),
    target_mode ENUM('AMOUNT', 'MONTHS') NOT NULL,
    target_months INTEGER
);

CREATE TABLE financial_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount NUMERIC(19, 2) NOT NULL,
    borrower_id BIGINT,
    category_id BIGINT,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    date DATE NOT NULL,
    description VARCHAR(1000),
    fee NUMERIC(19, 2),
    from_account_id BIGINT,
    holding_id BIGINT,
    kind ENUM('EXPENSE', 'INCOME', 'TRANSFER') NOT NULL,
    note VARCHAR(255),
    to_account_id BIGINT
);

CREATE TABLE holding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    current_value NUMERIC(19, 2) NOT NULL,
    invested_amount NUMERIC(19, 2) NOT NULL,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE holding_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    current_value NUMERIC(19, 2) NOT NULL,
    date DATE NOT NULL,
    holding_id BIGINT NOT NULL,
    invested_amount NUMERIC(19, 2) NOT NULL
);

CREATE TABLE ledger_bucket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_buffer BOOLEAN NOT NULL,
    closed_at DATE,
    end_date DATE,
    frequency_months INTEGER,
    monthly_allocation NUMERIC(19, 2) NOT NULL,
    name VARCHAR(255) NOT NULL,
    next_payment_date DATE,
    payment_amount NUMERIC(19, 2),
    previous_payment_date DATE
);

CREATE TABLE ledger_detail (
    account_id BIGINT PRIMARY KEY
);

CREATE TABLE ledger_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount NUMERIC(19, 2) NOT NULL,
    bucket_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    date DATE NOT NULL,
    kind ENUM('ADJUST', 'CLOSE_IN', 'CLOSE_OUT', 'FUND', 'INTEREST', 'MOVE_IN', 'MOVE_OUT', 'OPENING', 'PAY') NOT NULL,
    note VARCHAR(255),
    transaction_id BIGINT
);

CREATE TABLE note (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    body VARCHAR(10000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    date DATE NOT NULL,
    title VARCHAR(200),
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE note_tag (
    note_id BIGINT NOT NULL,
    tag VARCHAR(30) NOT NULL,
    PRIMARY KEY (note_id, tag),
    FOREIGN KEY (note_id) REFERENCES note (id)
);

CREATE TABLE portfolio_detail (
    account_id BIGINT PRIMARY KEY,
    kind ENUM('MUTUAL_FUNDS', 'SHARES') NOT NULL UNIQUE,
    total_invested NUMERIC(19, 2)
);

CREATE TABLE reminder (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    date DATE NOT NULL,
    done BOOLEAN NOT NULL,
    done_on DATE,
    repeat_every VARCHAR(10) DEFAULT 'NONE' NOT NULL,
    title VARCHAR(200) NOT NULL
);

CREATE TABLE ring_fence (
    account_id BIGINT PRIMARY KEY,
    fenced_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE vehicle_detail (
    account_id BIGINT PRIMARY KEY,
    number_plate VARCHAR(20),
    value_updated_on DATE,
    year_bought INTEGER
);
