-- A debt somebody owes you that you let go of: how much, on what day and why. It lowers what that person owes and the Receivables total; it is not a
-- transaction (no account is involved), so income, expenses and net worth (which leaves Receivables out) are untouched.
CREATE TABLE loan_write_off (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    borrower_id BIGINT NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    written_on DATE NOT NULL,
    note VARCHAR(255) NOT NULL
);
