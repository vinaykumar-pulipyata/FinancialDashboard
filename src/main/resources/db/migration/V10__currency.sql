-- Accounts can be held in a currency other than rupees. Existing accounts are rupees. Rates are rupees per 1 unit of the currency,
-- entered by hand: the rate used on a day is the latest one on or before it.
ALTER TABLE account ADD COLUMN currency VARCHAR(3) NOT NULL DEFAULT 'INR';

CREATE TABLE exchange_rate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency VARCHAR(3) NOT NULL,
    rate_date DATE NOT NULL,
    rate NUMERIC(19, 8) NOT NULL,
    CONSTRAINT uq_exchange_rate UNIQUE (currency, rate_date)
);
