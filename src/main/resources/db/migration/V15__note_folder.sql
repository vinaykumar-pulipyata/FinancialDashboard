-- Folders for notes. A note with no folder is a Daily Calendar Note (the diary); a note in a folder is a general one (Recipes, Study Materials...).
-- Every note keeps its date and still shows on the Calendar. A folder with notes in it cannot be deleted.
CREATE TABLE note_folder (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL
);
ALTER TABLE note ADD COLUMN folder_id BIGINT;
ALTER TABLE note ADD FOREIGN KEY (folder_id) REFERENCES note_folder (id);
