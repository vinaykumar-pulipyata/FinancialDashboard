-- Jewellery: gold, silver and other items you own, kept as items (name, form, weight, price paid) inside one Jewellery account.
-- The account.type ENUM gets the new value; GOLD stays so older Gold accounts keep working.
ALTER TABLE account ALTER COLUMN type ENUM('BANK', 'CASH', 'CREDIT_CARD', 'DEBT', 'GOAL_FUND', 'GOLD', 'INVESTMENT', 'JEWELLERY', 'OTHER', 'PROPERTY', 'RECEIVABLE', 'VEHICLE', 'WALLET') NOT NULL;

CREATE TABLE jewellery_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    metal VARCHAR(40) NOT NULL,
    form VARCHAR(12) NOT NULL,
    name VARCHAR(100) NOT NULL,
    weight NUMERIC(19, 3) NOT NULL,
    bought_price NUMERIC(19, 2) NOT NULL
);
