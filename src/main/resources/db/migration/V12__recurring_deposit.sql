-- Recurring Deposits: one INVESTMENT account (a row in recurring_deposit_detail marks it, like portfolio_detail does for Mutual Funds)
-- and, inside it, one row per deposit with its term. A deposit is opened and later closed, never deleted, so its history stays.
-- Deposits and the payout are ordinary transfers that carry the id of their deposit in financial_transaction.recurring_deposit_id.
CREATE TABLE recurring_deposit_detail (
    account_id BIGINT PRIMARY KEY
);

CREATE TABLE recurring_deposit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    start_date DATE NOT NULL,
    term_months INT NOT NULL,
    monthly_amount NUMERIC(19, 2),
    interest_rate NUMERIC(6, 3),
    already_deposited NUMERIC(19, 2) NOT NULL,
    status VARCHAR(10) NOT NULL,
    closed_on DATE,
    received_amount NUMERIC(19, 2)
);

ALTER TABLE financial_transaction ADD COLUMN recurring_deposit_id BIGINT;
