-- Splitting an expense with people (the Receivables list). An expense keeps its full amount; transaction_split holds what each other person owes
-- of it (the user's own share is the amount less these). split_settlement records which part of a payment from a person cleared which split
-- expense, so every settlement shows what it covered. Only new tables: no existing row is changed.
CREATE TABLE transaction_split (
    transaction_id BIGINT NOT NULL,
    borrower_id BIGINT NOT NULL,
    share NUMERIC(19, 2) NOT NULL,
    PRIMARY KEY (transaction_id, borrower_id),
    FOREIGN KEY (transaction_id) REFERENCES financial_transaction (id)
);

CREATE TABLE split_settlement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    borrower_id BIGINT NOT NULL,
    expense_transaction_id BIGINT NOT NULL,
    income_transaction_id BIGINT NOT NULL,
    amount NUMERIC(19, 2) NOT NULL
);
